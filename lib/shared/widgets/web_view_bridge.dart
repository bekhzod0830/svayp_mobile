import 'package:flutter/foundation.dart';

/// Шина «натив → вебвью» для событий, которые происходят вне вебвью.
///
/// Зачем: баланс алмазов живёт в состоянии React внутри таба Гардероба, а этот таб сидит
/// в [IndexedStack] и НЕ перемонтируется. Промокод же применяется в нативном экране профиля.
/// Без явного пинка человек применил бы бонусный код и не увидел начисленных алмазов —
/// со стороны это выглядит как «промокод не сработал».
///
/// Тот же приём, что уже используется для темы и языка (`__setNativeTheme` /
/// `__setNativeLocale`): вебвью выставляет глобальную функцию, натив её дёргает.
class WebViewBridge {
  WebViewBridge._();

  /// Счётчик запросов на обновление баланса. Живые [WebViewScreen] слушают его
  /// и выполняют `window.__svaypRefreshCoins()` в загруженной странице.
  static final ValueNotifier<int> coinsRefreshTick = ValueNotifier<int>(0);

  /// Попросить вебвью перечитать баланс монет.
  static void requestCoinsRefresh() => coinsRefreshTick.value++;
}
